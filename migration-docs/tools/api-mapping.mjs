function expressRouteFile(method, p) {
  const ep = toExpress(p);
  const needle = new RegExp(`\\.${method.toLowerCase()}\\(\\s*'${ep.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}'`);
  for (const [file, src] of routeFiles) if (needle.test(src)) return path.relative(EXPRESS, file).replace(/\\/g, '/');
  return null;
}

function testsFor(p) {
  const ep = p.replace(/^\/api/, '');
  const base = ep.split('/{')[0];
  const parametrised = ep.includes('{');
  const hits = testFiles.filter(
    ([, src]) =>
      src.includes(`'/api${ep}'`) ||
      src.includes(`\`/api${base}`) ||
      src.includes(`'/api${base}'`) ||
      src.includes(`"/api${base}"`) ||
      // Helpers that prepend /api internally, e.g. call('POST', 'ecxelUpload', ...).
      src.includes(`, '${ep.slice(1)}',`) ||
      // concrete ids in tests, e.g. '/api/sessions/contract-session-1' for /sessions/{session}
      (parametrised && src.includes(`'/api${base}/`)),
  );
  return hits.map(([f]) => path.basename(f));
}

const rows = routes.map((r) => {
  const method = r.method;
  const ep = toExpress(r.path);
  const file = expressRouteFile(method, r.path) ?? (method === 'PATCH' ? expressRouteFile('PATCH', r.path) : null);
  const tests = testsFor(r.path);
  let status;
  if (/\/edit$/.test(ep)) status = 'IMPLEMENTED (500 parity: no edit())';
  else if (!file) status = 'NOT STARTED';
  else if (tests.length) status = 'COVERED';
  else status = 'IMPLEMENTED';
  return { ...r, file, tests, status, dev: file?.endsWith('recovered.routes.js') ? 'FIX-RECOVERED (documented recovery contract)' : DEVIATIONS[ep] ?? DEVIATIONS[ep.replace(/\/:\w+$/, '/:user')] ?? '' };
});

