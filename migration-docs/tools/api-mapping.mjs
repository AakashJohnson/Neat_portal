import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const EXPRESS = path.join(ROOT, 'express-backend');
const { routes } = JSON.parse(readFileSync(path.join(import.meta.dirname, '..', 'generated', 'api-routes.json'), 'utf8'));

const read = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? read(path.join(dir, d.name)) : d.name.endsWith('.js') ? [[path.join(dir, d.name), readFileSync(path.join(dir, d.name), 'utf8')]] : [],
  );
const routeFiles = read(path.join(EXPRESS, 'src', 'routes'));
// Expand `${prefix}` template paths used by parameterised tests ('' | B2B | B2C).
const testFiles = read(path.join(EXPRESS, 'tests')).map(([f, src]) => [f, ['', 'B2B', 'B2C'].map((p) => src.replaceAll('${prefix}', p)).join('\n')]);

// Laravel {param} → Express :param
const toExpress = (p) => p.replace(/^\/api/, '').replace(/\{(\w+)\}/g, ':$1');

