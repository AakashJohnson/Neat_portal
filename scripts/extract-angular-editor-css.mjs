// Ports the styles of @kolkov/angular-editor 1.1.2 (the rich-text editor of
// the company product form) to public/legacy/angular-editor.css:
//   - AngularEditorToolbarComponent / AngularEditorComponent use emulated
//     encapsulation: their rules are scoped to the host tag the React port
//     renders (<angular-editor-toolbar>, <angular-editor>) and kept out of
//     child-component templates and of the editable content, except after
//     ::ng-deep (as Angular's shim does).
//   - AeSelectComponent uses ViewEncapsulation.None: copied as is.
// @font-face / @keyframes stay global. The page links this file only where an
// editor renders, as Angular injects component styles on first use.
//   node scripts/extract-angular-editor-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';

const APP = path.resolve(import.meta.dirname, '..');
const BUNDLE = path.resolve(APP, '..', '..', 'NEAT portal old', 'frontend', 'frontend', 'node_modules', '@kolkov', 'angular-editor', 'fesm2015', 'kolkov-angular-editor.js');

/** styles: [...] of the component whose selector is `selector`. */
function componentStyles(src, selector) {
  const at = src.indexOf(`selector: '${selector}'`);
  const line = src.slice(at).split('\n').find((l) => l.trimStart().startsWith('styles: ['));
  return JSON.parse(line.trim().replace(/^styles: /, '').replace(/,?\s*$/, '')).join('\n');
}

const isPseudoElement = (n) => n.type === 'pseudo' && (n.value.startsWith('::') || /^:(before|after|first-line|first-letter)$/i.test(n.value));

function scope(css, host, foreign) {
  const root = postcss.parse(css);
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    rule.selector = selectorParser((sels) => {
      sels.each((s) => {
        const deep = s.nodes.find((n) => n.type === 'pseudo' && n.value === '::ng-deep');
        if (deep) {
          // `A ::ng-deep B` → A scoped, B unrestricted.
          const next = deep.next();
          if (next?.type === 'combinator') next.remove();
          const prev = deep.prev();
          deep.remove();
          if (prev?.type === 'combinator') prev.value = ' ';
        } else {
          let last = s.last;
          while (last && isPseudoElement(last)) last = last.prev();
          if (last && last.type !== 'combinator') s.insertAfter(last, selectorParser.pseudo({ value: `:not(${foreign})` }));
        }
        s.prepend(selectorParser.combinator({ value: ' ' }));
        s.prepend(selectorParser.tag({ value: host }));
      });
    }).processSync(rule.selector);
  });
  return root.toString();
}

const src = readFileSync(BUNDLE, 'utf8');
const out = [
  '/* generated by scripts/extract-angular-editor-css.mjs from @kolkov/angular-editor 1.1.2 — do not edit */',
  '/* ---- AngularEditorToolbarComponent (emulated) ---- */',
  scope(componentStyles(src, 'angular-editor-toolbar'), 'angular-editor-toolbar', 'ae-select *'),
  '/* ---- AngularEditorComponent (emulated) ---- */',
  scope(componentStyles(src, 'angular-editor'), 'angular-editor', 'angular-editor-toolbar *, .angular-editor-textarea *'),
  '/* ---- AeSelectComponent (ViewEncapsulation.None) ---- */',
  componentStyles(src, 'ae-select'),
].join('\n');
writeFileSync(path.join(APP, 'public', 'legacy', 'angular-editor.css'), out + '\n');
console.log(`angular-editor.css: ${out.length} bytes`);
