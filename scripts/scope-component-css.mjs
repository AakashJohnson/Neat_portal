// Ports Angular component styles (*.component.css, emulated encapsulation) to
// one static stylesheet: every selector of component X is prefixed with
// `.ngc-X`, and the React port wraps X's markup in <Scope name="X"> (a
// `display: contents` element), so the rules only reach that component's DOM.
//   node scripts/scope-component-css.mjs  → public/legacy/components.css
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';

const APP = path.resolve(import.meta.dirname, '..');
const NG_APP = path.resolve(APP, '..', 'frontend', 'frontend', 'src', 'app');

function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const f = path.join(dir, n);
    if (statSync(f).isDirectory()) walk(f, out);
    else if (n.endsWith('.component.css')) out.push(f);
  }
  return out;
}

/** Component name = file name without ".component.css" (e.g. "navbar", "admin-dashboard"). */
export const scopeName = (file) => path.basename(file, '.component.css');

function prefixSelector(sel, scope) {
  return selectorParser((root) => {
    root.each((s) => {
      // :host / :host(.x) → the scope element itself.
      let hostHandled = false;
      s.walkPseudos((p) => {
        if (p.value === ':host') {
          const inner = p.nodes.length ? String(p.nodes[0]) : '';
          p.replaceWith(selectorParser.className({ value: `ngc-${scope}${inner ? '' : ''}` }));
          if (inner) s.insertAfter(s.first, selectorParser.string({ value: inner }));
          hostHandled = true;
        } else if (p.value === '::ng-deep' || p.value === '/deep/') {
          p.remove();
        }
      });
      if (!hostHandled) {
        s.prepend(selectorParser.combinator({ value: ' ' }));
        s.prepend(selectorParser.className({ value: `ngc-${scope}` }));
      }
    });
  }).processSync(sel);
}

let out = '/* generated by scripts/scope-component-css.mjs from src/app/**\/*.component.css — do not edit */\n';
const names = [];
for (const file of walk(NG_APP)) {
  const css = readFileSync(file, 'utf8').replace(/^﻿/, '');
  if (!css.trim()) continue;
  const scope = scopeName(file);
  names.push(scope);
  let root;
  try {
    root = postcss.parse(css, { from: file });
  } catch (err) {
    out += `\n/* ${scope}: skipped, unparsable in original (${err.reason}) */\n`;
    continue;
  }
  root.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    try {
      rule.selector = prefixSelector(rule.selector, scope);
    } catch {
      rule.selector = `.ngc-${scope} ${rule.selector}`;
    }
  });
  out += `\n/* ---- ${path.relative(NG_APP, file).replace(/\\/g, '/')} ---- */\n${root.toString()}\n`;
}
mkdirSync(path.join(APP, 'public', 'legacy'), { recursive: true });
writeFileSync(path.join(APP, 'public', 'legacy', 'components.css'), out);
console.log(`scoped ${names.length} component stylesheets: ${names.join(', ')}`);
