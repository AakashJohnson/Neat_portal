// Angular Material 7 components inject their structural CSS at runtime (the
// `styles: [...]` of each component, ViewEncapsulation.None). The prebuilt
// theme in legacy.css only supplies colours/typography. This extracts those
// component styles from the installed @angular/material (read-only) into
// public/legacy/material.css so the ported mat-* markup renders identically.
//   node scripts/extract-material-css.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const APP = path.resolve(import.meta.dirname, '..');
const ESM = path.resolve(APP, '..', 'frontend', 'frontend', 'node_modules', '@angular', 'material', 'esm2015');
const version = JSON.parse(readFileSync(path.join(ESM, '..', 'package.json'), 'utf8')).version;

const STYLES = /styles:\s*\[((?:\s*"(?:[^"\\]|\\.)*"\s*,?)+)\s*\]/g;
const STRING = /"(?:[^"\\]|\\.)*"/g;

// core first (ripple, option, pseudo-checkbox), then alphabetical.
const files = readdirSync(ESM)
  .filter((f) => f.endsWith('.js') && f !== 'material.js')
  .sort((a, b) => (a === 'core.js' ? -1 : b === 'core.js' ? 1 : a.localeCompare(b)));

let out = `/* generated by scripts/extract-material-css.mjs from @angular/material ${version} — do not edit */\n`;
let count = 0;
for (const f of files) {
  const js = readFileSync(path.join(ESM, f), 'utf8');
  const seen = new Set();
  for (const m of js.matchAll(STYLES)) {
    for (const s of m[1].match(STRING)) {
      const css = JSON.parse(s);
      if (!css.trim() || seen.has(css)) continue;
      seen.add(css);
      out += `\n/* ---- ${f} ---- */\n${css}\n`;
      count++;
    }
  }
}
writeFileSync(path.join(APP, 'public', 'legacy', 'material.css'), out);
console.log(`material.css: ${count} component stylesheets from @angular/material ${version}`);
