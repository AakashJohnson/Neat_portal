import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import { chromium, expect } from '@playwright/test';
import { startServer } from '../server/server.mjs';

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'neat-architecture-browser-'));
const pageFile = path.join(root, 'nextjs-frontend', 'src', 'app', 'page.jsx');
let browser, running;
const errors = [];
try {
  await fs.mkdir(path.dirname(pageFile), { recursive: true });
  await fs.writeFile(pageFile, "export default function ArchitectureDemo(){ return <div>Architecture</div>; }");
  await fs.writeFile(path.join(root, 'schema.sql'), 'CREATE TABLE users (id INT PRIMARY KEY, name VARCHAR(50));');
  const probe = http.createServer();
  await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  running = await startServer({ root, port });
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(running.url);
  await expect(page.locator('.statusbar')).toContainText('READY');
  await expect(page.locator('.react-flow__node')).toHaveCount(2);
  await expect(page.getByRole('img', { name: 'Mini Map' })).toBeVisible();
  await page.getByRole('button', { name: 'SQL schema' }).click();
  await expect(page.locator('.schema-banner')).toContainText('1 tables, 2 columns');
  await page.locator('.react-flow__node').filter({ hasText: 'users' }).click();
  await expect(page.locator('.inspector')).toContainText('Schema details');
  await expect(page.locator('.inspector')).toContainText('schema.sql');
  await page.getByRole('button', { name: 'Next.js frontend' }).click();
  const node = page.locator('.react-flow__node').filter({ hasText: 'ArchitectureDemo' }).first();
  await expect(node).toBeVisible();
  const box = await node.boundingBox();
  const original = await node.getAttribute('style');
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2 + 40, { steps: 8 }); await page.mouse.up();
  await expect(node).not.toHaveAttribute('style', original);
  await page.getByRole('button', { name: /^zoom in$/i }).click();
  await page.getByRole('button', { name: /^fit view$/i }).click();
  await page.getByRole('textbox', { name: 'Search architecture' }).fill('ArchitectureDemo');
  await expect(page.locator('.search-results')).toContainText('ArchitectureDemo');
  await page.locator('.search-results button').first().click();
  await expect(page.locator('.inspector h2')).toHaveText('ArchitectureDemo');
  await page.getByRole('checkbox', { name: 'frontend', exact: true }).uncheck();
  await expect(page.getByRole('heading', { name: 'No matching nodes' })).toBeVisible();
  await page.getByRole('checkbox', { name: 'frontend', exact: true }).check();
  await page.getByRole('button', { name: 'System overview' }).click();
  await page.evaluate(() => { window.__noReloadMarker = 'retained'; });
  await fs.writeFile(pageFile, "export default function LiveRefreshVerified(){return <div/>;}");
  await expect.poll(() => page.locator('.statusbar').innerText()).toContain('Revision 2');
  await page.getByRole('textbox', { name: 'Search architecture' }).fill('LiveRefreshVerified');
  await expect(page.locator('.search-results')).toContainText('LiveRefreshVerified');
  expect(await page.evaluate(() => window.__noReloadMarker)).toBe('retained');
  await page.getByRole('button', { name: 'Rescan repository' }).click();
  await expect.poll(() => page.locator('.statusbar').innerText()).toContain('Revision 3');
  await page.getByRole('button', { name: 'Evidence & limits' }).click();
  await expect(page.getByRole('dialog')).toContainText('No database connection');
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.setViewportSize({ width: 820, height: 740 });
  await expect(page.getByRole('textbox', { name: 'Search architecture' })).toBeVisible();
  expect(errors).toEqual([]);
  console.log('Browser PASS: graph, ER metadata, inspector, search, filters, drag, zoom, fit, manual scan, live SSE refresh without reload, responsive layout, zero page errors.');
} finally {
  await browser?.close();
  await running?.close();
  await fs.rm(root, { recursive: true, force: true });
}
